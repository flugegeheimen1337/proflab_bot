def explain_error(exc: Exception) -> str:
    detail = getattr(exc, "detail", None) or getattr(exc, "code", "")
    code = getattr(exc, "code", detail)
    if isinstance(detail, str) and (detail.startswith("length:") or detail in {"file_too_large", "empty", "type", "file"}):
        return explain(detail)
    return explain(str(code))


def explain(code: str) -> str:
    if code.startswith("length:"):
        return f"Слишком длинное сообщение. Лимит — {code.split(':', 1)[1]} символов."
    if code == "file_too_large":
        return "Файл больше 15 МБ. Отправьте меньший: бот заново загружает видео и документы без исходного имени."
    if code == "empty":
        return "Пустое сообщение не отправляется."
    if code == "type":
        return "Этот тип сообщения в группе не разрешён."
    if code == "file":
        return "Не удалось прочитать файл."
    return ERRORS.get(code, "Не получилось обработать сообщение.")


